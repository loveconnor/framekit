import postcss from "postcss";
import type { Breakpoint, StyleRules, StyleSheetModel } from "@/types/elements";

export const BREAKPOINT_QUERY: Record<Exclude<Breakpoint, "desktop">, string> = {
  tablet: "(max-width: 1023px)",
  mobile: "(max-width: 767px)",
};

const HEADER = `/* Generated by Framekit. Edit visually in Framekit or by hand; keep one rule per element id. */`;

export function selectorFor(styleId: string): string {
  return `[data-fk-style="${styleId}"]`;
}

/** Deterministic CSS: base rules, then tablet, then mobile, each sorted by style id. */
export function serializeStylesheet(model: StyleSheetModel): string {
  const ids = Object.keys(model).sort();
  const blocks: string[] = [HEADER];

  const rulesFor = (bp: Breakpoint, indent: string): string[] => {
    const out: string[] = [];
    for (const id of ids) {
      const decls = model[id]?.[bp];
      if (!decls) continue;
      const props = Object.keys(decls).sort();
      if (props.length === 0) continue;
      out.push(`${indent}${selectorFor(id)} {`);
      for (const prop of props) out.push(`${indent}  ${prop}: ${decls[prop]};`);
      out.push(`${indent}}`);
    }
    return out;
  };

  const base = rulesFor("desktop", "");
  if (base.length) blocks.push(base.join("\n"));
  for (const bp of ["tablet", "mobile"] as const) {
    const rules = rulesFor(bp, "  ");
    if (rules.length) blocks.push(`@media ${BREAKPOINT_QUERY[bp]} {\n${rules.join("\n")}\n}`);
  }
  return blocks.join("\n\n") + "\n";
}

/** Read a stylesheet Framekit wrote earlier. Rules it does not recognize are dropped with a warning list. */
export function parseStylesheet(css: string): { model: StyleSheetModel; warnings: string[] } {
  const model: StyleSheetModel = {};
  const warnings: string[] = [];
  const root = postcss.parse(css);

  const readRule = (rule: postcss.Rule, bp: Breakpoint) => {
    const match = rule.selector.match(/^\[data-fk-style="([^"]+)"\]$/);
    if (!match) {
      warnings.push(`Unrecognized selector ignored: ${rule.selector}`);
      return;
    }
    const id = match[1];
    const decls: Record<string, string> = {};
    rule.walkDecls((d) => {
      decls[d.prop] = d.important ? `${d.value} !important` : d.value;
    });
    model[id] = model[id] ?? {};
    model[id][bp] = { ...(model[id][bp] ?? {}), ...decls };
  };

  root.each((node) => {
    if (node.type === "rule") readRule(node, "desktop");
    else if (node.type === "atrule" && node.name === "media") {
      const params = node.params.replace(/\s+/g, " ").trim();
      const bp = (Object.keys(BREAKPOINT_QUERY) as Array<keyof typeof BREAKPOINT_QUERY>).find((k) => BREAKPOINT_QUERY[k] === params);
      if (!bp) {
        warnings.push(`Unrecognized media query ignored: @media ${params}`);
        return;
      }
      node.each((child) => {
        if (child.type === "rule") readRule(child, bp);
      });
    }
  });
  return { model, warnings };
}

export function setStyle(model: StyleSheetModel, styleId: string, bp: Breakpoint, property: string, value: string | null): StyleSheetModel {
  const next: StyleSheetModel = { ...model };
  const rules: StyleRules = { ...(next[styleId] ?? {}) };
  const decls = { ...(rules[bp] ?? {}) };
  if (value === null) delete decls[property];
  else decls[property] = value;
  if (Object.keys(decls).length === 0) delete rules[bp];
  else rules[bp] = decls;
  if (Object.keys(rules).length === 0) delete next[styleId];
  else next[styleId] = rules;
  return next;
}

export function removeStyleIds(model: StyleSheetModel, ids: Iterable<string>): StyleSheetModel {
  const next = { ...model };
  for (const id of ids) delete next[id];
  return next;
}

export function copyStyleRules(model: StyleSheetModel, pairs: Array<{ from: string; to: string }>): StyleSheetModel {
  const next = { ...model };
  for (const { from, to } of pairs) {
    if (next[from]) next[to] = JSON.parse(JSON.stringify(next[from]));
  }
  return next;
}

const ID_ALPHABET = "abcdefghijklmnopqrstuvwxyz0123456789";

export function makeStyleIdFactory(taken: Set<string>): () => string {
  return () => {
    for (let attempt = 0; attempt < 100; attempt++) {
      let id = "fk-";
      for (let i = 0; i < 4 + Math.floor(attempt / 10); i++) id += ID_ALPHABET[Math.floor(Math.random() * ID_ALPHABET.length)];
      if (!taken.has(id)) {
        taken.add(id);
        return id;
      }
    }
    throw new Error("Could not allocate a unique style id");
  };
}

