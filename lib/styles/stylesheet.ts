/** `url()` is only allowed for same-origin absolute paths (`/images/x.png`): no schemes, no protocol-relative URLs. */
const SAFE_URL = /url\(\s*(['"]?)(\/(?!\/)[^'"()\s\\]*)\1\s*\)/gi;

/** Keep generated CSS to a known vocabulary and refuse anything that could smuggle in extra rules. */
export function validateDeclaration(property: string, value: string): string | null {
  if (!ALLOWED_PROPERTIES.has(property)) return `The ${property} property isn't supported.`;
  if (value.length > 200) return "That value is too long.";
  const withoutSafeUrls = value.replace(SAFE_URL, "url()");
  if (/[;{}<>]|\/\*|expression\(|@import/i.test(withoutSafeUrls)) return "That value contains characters that aren't allowed.";
  if (/url\((?!\))/i.test(withoutSafeUrls)) return "Only images from this project's public folder can be used.";
  if (value.includes("!important")) return "Framekit doesn't write !important.";
  if (/^padding-/.test(property) && /^-/.test(value.trim())) return "Padding can't be negative.";
  if (property === "opacity") {
    const n = Number(value);
    if (Number.isNaN(n) || n < 0 || n > 1) return "Opacity must be between 0 and 1.";
  }
  return null;
}
